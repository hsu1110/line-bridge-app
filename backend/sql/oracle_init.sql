-- =========================================================================
-- LINE Message Bridge - Oracle 跨版本相容建表腳本 (相容 11g / 12c / 19c+)
-- 說明：
--   1. 所有表名使用 LB_ 前綴，避開 USER/GROUP/LOG/MODE 等 Oracle 保留字
--   2. 主鍵統一使用 VARCHAR2(36) UUID，避免 11g 無 IDENTITY 語法的差異
--   3. 長文字 / Token / JSON 統一使用 CLOB，避免超過 VARCHAR2(4000) 上限
--   4. 布林旗標使用 NUMBER(1) (1=是, 0=否)
-- =========================================================================

-- 1. LINE Bot 官方帳號設定表
CREATE TABLE LB_BOT_ACCOUNT (
    ID                    VARCHAR2(36)   NOT NULL,
    BOT_CODE              VARCHAR2(64)   NOT NULL,
    NAME                  VARCHAR2(100)  NOT NULL,
    LINE_BOT_USER_ID      VARCHAR2(64),
    LINE_BASIC_ID         VARCHAR2(64),
    CHANNEL_ACCESS_TOKEN  CLOB           NOT NULL,
    CHANNEL_SECRET        VARCHAR2(256)  NOT NULL,
    QUOTA_LIMIT           NUMBER(10)     DEFAULT 200 NOT NULL,
    ENABLED               NUMBER(1)      DEFAULT 1 NOT NULL,
    WELCOME_ENABLED       NUMBER(1)      DEFAULT 1 NOT NULL,
    WELCOME_MESSAGE       CLOB,
    CREATED_AT            TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT            TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LB_BOT_ACCOUNT PRIMARY KEY (ID),
    CONSTRAINT UK_LB_BOT_CODE UNIQUE (BOT_CODE)
);

-- 2. 通訊錄（個人 / 群組 / 聊天室）
CREATE TABLE LB_CONTACT (
    ID            VARCHAR2(36)   NOT NULL,
    CODE          VARCHAR2(100),
    NAME          VARCHAR2(200)  NOT NULL,
    LINE_ID       VARCHAR2(64)   NOT NULL,
    CONTACT_TYPE  VARCHAR2(20)   NOT NULL,
    CREATED_AT    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LB_CONTACT PRIMARY KEY (ID),
    CONSTRAINT UK_LB_CONTACT_CODE UNIQUE (CODE),
    CONSTRAINT UK_LB_CONTACT_LINE_ID UNIQUE (LINE_ID)
);

-- 3. 聯絡人與 Bot 多對多綁定關係表
CREATE TABLE LB_CONTACT_BOT (
    ID          VARCHAR2(36)  NOT NULL,
    CONTACT_ID  VARCHAR2(36)  NOT NULL,
    BOT_ID      VARCHAR2(36)  NOT NULL,
    BOUND_AT    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LB_CONTACT_BOT PRIMARY KEY (ID),
    CONSTRAINT UK_LB_CONTACT_BOT UNIQUE (CONTACT_ID, BOT_ID)
);

CREATE INDEX IDX_LB_CB_BOT_ID ON LB_CONTACT_BOT (BOT_ID);

-- 4. 訊息模板表
CREATE TABLE LB_TEMPLATE (
    ID             VARCHAR2(36)   NOT NULL,
    CODE           VARCHAR2(100)  NOT NULL,
    NAME           VARCHAR2(200)  NOT NULL,
    CONTENT        CLOB           NOT NULL,
    REQUIRED_VARS  VARCHAR2(1000),
    DESCRIPTION    VARCHAR2(500),
    CREATED_AT     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LB_TEMPLATE PRIMARY KEY (ID),
    CONSTRAINT UK_LB_TEMPLATE_CODE UNIQUE (CODE)
);

-- 5. 外部呼叫系統 API Client（多系統 API Key 與權限控管）
CREATE TABLE LB_API_CLIENT (
    ID                      VARCHAR2(36)   NOT NULL,
    CLIENT_CODE             VARCHAR2(64)   NOT NULL,
    CLIENT_NAME             VARCHAR2(100)  NOT NULL,
    API_KEY                 VARCHAR2(128)  NOT NULL,
    ALLOWED_BOT_CODES       VARCHAR2(1000),
    ALLOWED_TEMPLATE_CODES  VARCHAR2(1000),
    RATE_LIMIT_PER_MIN      NUMBER(10)     DEFAULT 60 NOT NULL,
    ENABLED                 NUMBER(1)      DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT              TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LB_API_CLIENT PRIMARY KEY (ID),
    CONSTRAINT UK_LB_CLIENT_CODE UNIQUE (CLIENT_CODE),
    CONSTRAINT UK_LB_CLIENT_API_KEY UNIQUE (API_KEY)
);

-- 6. 訊息發送紀錄與非同步任務表
CREATE TABLE LB_SEND_LOG (
    ID              VARCHAR2(36)   NOT NULL,
    CLIENT_ID       VARCHAR2(36),
    CLIENT_NAME     VARCHAR2(100),
    BOT_ID          VARCHAR2(36),
    BOT_CODE        VARCHAR2(64),
    TARGET_CODE     VARCHAR2(100),
    TARGET_LINE_ID  VARCHAR2(64),
    TEMPLATE_CODE   VARCHAR2(100),
    CONTENT         CLOB,
    STATUS          VARCHAR2(20)   NOT NULL,
    RETRY_KEY       VARCHAR2(36),
    ERROR_MESSAGE   CLOB,
    SOURCE_IP       VARCHAR2(64),
    DURATION_MS     NUMBER(10),
    CREATED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LB_SEND_LOG PRIMARY KEY (ID)
);

CREATE INDEX IDX_LB_SEND_LOG_TIME ON LB_SEND_LOG (CREATED_AT);
CREATE INDEX IDX_LB_SEND_LOG_STATUS ON LB_SEND_LOG (STATUS);

-- 7. Webhook 接收除錯紀錄與事件去重表
CREATE TABLE LB_WEBHOOK_EVENT (
    ID                VARCHAR2(36)   NOT NULL,
    WEBHOOK_EVENT_ID  VARCHAR2(64),
    BOT_CODE          VARCHAR2(64),
    EVENT_TYPE        VARCHAR2(50),
    SOURCE_ID         VARCHAR2(64),
    SIGNATURE_VALID   NUMBER(1)      DEFAULT 0 NOT NULL,
    IS_REDELIVERY     NUMBER(1)      DEFAULT 0 NOT NULL,
    PROCESS_STATUS    VARCHAR2(20)   NOT NULL,
    RAW_PAYLOAD       CLOB,
    ERROR_MESSAGE     CLOB,
    CREATED_AT        TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LB_WEBHOOK_EVENT PRIMARY KEY (ID),
    CONSTRAINT UK_LB_WEBHOOK_EVENT_ID UNIQUE (WEBHOOK_EVENT_ID)
);

CREATE INDEX IDX_LB_WH_CREATED_AT ON LB_WEBHOOK_EVENT (CREATED_AT);
